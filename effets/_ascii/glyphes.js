// Blocs : [x0, y0, x1, y1] en huitièmes de case, plus les quadrants
const BLOCS = { "█": [0, 0, 8, 8], "▀": [0, 0, 8, 4], "▄": [0, 4, 8, 8], "▌": [0, 0, 4, 8], "▐": [4, 0, 8, 8], "▔": [0, 0, 8, 1], "▕": [7, 0, 8, 8] };
"▁▂▃▄▅▆▇".split("").forEach((c, i) => (BLOCS[c] = [0, 7 - i, 8, 8]));
"▉▊▋▌▍▎▏".split("").forEach((c, i) => (BLOCS[c] = [0, 0, 7 - i, 8]));
// quadrants : bits haut-gauche 1, haut-droite 2, bas-gauche 4, bas-droite 8
const QUADS = { "▖": 4, "▗": 8, "▘": 1, "▝": 2, "▙": 13, "▚": 9, "▛": 7, "▜": 11, "▞": 6, "▟": 14 };
const TRAMES = { "░": 0.25, "▒": 0.5, "▓": 0.75 };
// trames ordonnées (Bayer 4 × 4) : un pixel est encré quand la densité dépasse son seuil
const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5].map((v) => (v + 0.5) / 16);

/** Densité d'encre d'un caractère (0..1), pour les scènes en demi-teintes et les caractères inconnus. */
export function encre(c) {
  if (c === " ") return 0;
  if (c in NIVEAUX) return NIVEAUX[c];
  if (c in TRAMES) return TRAMES[c];
  const b = BLOCS[c];
  if (b) return ((b[2] - b[0]) * (b[3] - b[1])) / 64;
  const q = QUADS[c];
  if (q) return ((q & 1) + ((q >> 1) & 1) + ((q >> 2) & 1) + ((q >> 3) & 1)) / 4;
  const n = c.codePointAt(0);
  if (n >= 0x2800 && n <= 0x28ff) { let k = 0, v = n - 0x2800; while (v) (k += v & 1), (v >>= 1); return k / 8; }
  const g = P35[c] ?? P35[c.toUpperCase()];
  if (g) return Math.min(1, (g.split("#").length - 1) / 9);
  return 0.35;
}
// les niveaux ▁ … █ des scènes peintes (lib/scene.js) : l'encre que le lecteur d'origine leur donne
const NIVEAUX = { "▁": 0.135, "▂": 0.257, "▃": 0.378, "▄": 0.51, "▅": 0.635, "▆": 0.757, "▇": 0.878, "█": 1 };

/** Masque cw × ch d'un caractère : Uint8Array, 0 vide, 255 plein (les trames sont déjà tramées). */
export function masque(c, cw, ch) {
  const m = new Uint8Array(cw * ch);
  const set = (x, y, v = 255) => { if (x >= 0 && y >= 0 && x < cw && y < ch) m[y * cw + x] = v; };
  const rect = (x0, y0, x1, y1) => { for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) set(x, y); };
  if (c === " ") return m;
  const b = BLOCS[c];
  if (b) { rect(Math.round((b[0] * cw) / 8), Math.round((b[1] * ch) / 8), Math.round((b[2] * cw) / 8), Math.round((b[3] * ch) / 8)); return m; }
  const q = QUADS[c];
  if (q) {
    const mx = cw >> 1, my = ch >> 1;
    if (q & 1) rect(0, 0, mx, my);
    if (q & 2) rect(mx, 0, cw, my);
    if (q & 4) rect(0, my, mx, ch);
    if (q & 8) rect(mx, my, cw, ch);
    return m;
  }
  if (c in TRAMES) {
    for (let y = 0; y < ch; y++) for (let x = 0; x < cw; x++) if (TRAMES[c] > BAYER[((y & 3) << 2) | (x & 3)]) set(x, y);
    return m;
  }
  const n = c.codePointAt(0);
  if (n >= 0x2800 && n <= 0x28ff) {
    // braille : 2 colonnes × 4 lignes de points
    const bits = n - 0x2800, pos = [[0, 0], [0, 1], [0, 2], [1, 0], [1, 1], [1, 2], [0, 3], [1, 3]];
    pos.forEach(([px, py], i) => { if (bits & (1 << i)) set(Math.floor(((px + 0.25) * cw) / 2), Math.floor(((py + 0.25) * ch) / 4)); });
    return m;
  }
  const a = BOX[c];
  if (a) {
    const cx = (cw - 1) >> 1, cy = (ch - 1) >> 1;
    const vert = (t, y0, y1) => {
      for (let y = y0; y <= y1; y++) {
        if (t === 4 || t === 5) { if (y & 1) continue; }
        if (t === 3) (set(cx - 1, y), set(cx + 1, y));
        else (set(cx, y), t === 2 || t === 5 ? set(cx + 1, y) : 0);
      }
    };
    const horiz = (t, x0, x1) => {
      for (let x = x0; x <= x1; x++) {
        if ((t === 4 || t === 5) && x & 1) continue;
        if (t === 3) (set(x, cy - 1), set(x, cy + 1));
        else (set(x, cy), t === 2 || t === 5 ? set(x, cy + 1) : 0);
      }
    };
    const [h, d, bas, g] = a;
    if (h) vert(h, 0, cy);
    if (bas) vert(bas, cy, ch - 1);
    if (g) horiz(g, 0, cx);
    if (d) horiz(d, cx, cw - 1);
    return m;
  }
  if (c === "╱" || c === "╲" || c === "╳") {
    for (let y = 0; y < ch; y++) {
      const x = Math.floor(((y + 0.5) * cw) / ch);
      if (c !== "╲") set(cw - 1 - x, y);
      if (c !== "╱") set(x, y);
    }
    return m;
  }
  const g = P35[c] ?? P35[c.toUpperCase()];
  if (g) {
    const rows = g.split("|"), y0 = Math.max(0, (ch - 5) >> 1), x0 = 0, v = Math.round(255 * (PALE[c] ?? 1));
    // dans une case de moins de 5 pixels de haut, les lignes de la police sont échantillonnées
    const H = Math.min(5, ch);
    for (let y = 0; y < H; y++) {
      const r = rows[Math.floor((y * 5) / H)];
      for (let x = 0; x < Math.min(3, cw); x++) if (r[Math.floor((x * 3) / Math.min(3, cw))] === "#") set(x0 + x, y0 + y, v);
    }
    return m;
  }
  // inconnu : une tache tramée à sa densité
  const k = encre(c);
  for (let y = 1; y < ch - 1; y++) for (let x = 0; x < cw - 1; x++) if (k > BAYER[((y & 3) << 2) | (x & 3)]) set(x, y);
  return m;
}
